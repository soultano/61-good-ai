window.applyLang = function (lang) {
  const d = window.I18N[lang] || window.I18N.ru;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = d[el.dataset.i18n];
    if (v !== undefined) el.innerHTML = v;
  });
  document.querySelectorAll("[data-lang]").forEach(b => b.classList.toggle("on", b.dataset.lang === lang));
  try { localStorage.setItem("lang", lang); } catch (e) {}
  if (window.onLang) window.onLang(lang);
};

window.initLang = function () {
  let l = null;
  try { l = new URLSearchParams(location.search).get("lang") || localStorage.getItem("lang"); } catch (e) {}
  if (!l) l = (navigator.language || "ru").slice(0, 2);
  if (!window.I18N[l]) l = "ru";
  document.querySelectorAll("[data-lang]").forEach(b => b.addEventListener("click", () => window.applyLang(b.dataset.lang)));
  window.applyLang(l);
};
